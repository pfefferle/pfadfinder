def test_store_manifest():
    m = json.loads((ROOT / "app-builder.json").read_text())
    assert m["package_name"] == "pfadfinder" and m["bin_name"] == "pfadfinder" and m["app_name"] == "Pfadfinder"
    assert m["version"] == pfadfinder.__version__
    s = m["store"]
    for key in ("summary", "categories", "screenshots", "icon", "license", "author", "share_code", "permissions"):
        assert key in s, key
    assert len(s["summary"]) <= 80
    assert 1 <= len(s["categories"]) <= 2
    assert set(s["permissions"]) == {"camera", "microphone", "imu", "network", "additional_hardware",
                                     "background_service", "external_display"}
    assert all(isinstance(v, bool) for v in s["permissions"].values())
    assert re.fullmatch(r"[A-Za-z0-9]{4}", s["share_code"])
    assert s["author"]["display_name"]
    for shot in s["screenshots"]:
        assert Image.open(ROOT / shot).size == (320, 170)
    w, h = Image.open(ROOT / s["icon"]).size
    assert w == h and 128 <= w <= 512


def test_no_ai_mentions_in_project_files():
    pattern = re.compile(r"\b(AI|A\.I\.|Claude|Anthropic|LLM|ChatGPT)\b|generated by", re.IGNORECASE)
    skip = {".superpowers", "build", ".git", "__pycache__"}
    offenders = []
    for p in ROOT.rglob("*"):
        rel = p.relative_to(ROOT)
        if not p.is_file() or set(rel.parts) & skip or rel.parts[:2] == ("docs", "superpowers"):
            continue
        if p.suffix in (".png", ".gz", ".deb"):
            continue
        if rel.as_posix() == "tests/test_packaging.py":
            continue
        if pattern.search(p.read_text(errors="ignore")):
            offenders.append(str(rel))
    assert offenders == []


