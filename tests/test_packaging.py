def _run_postinst_for(user: str):
    """Run the real postinst inside the (throwaway, root) test container."""
    if subprocess.run(["id", "-u", user], capture_output=True).returncode != 0:
        subprocess.run(["useradd", "-m", "-u", "1000", user], check=True)
    subprocess.run(["sh", str(ROOT / "packaging/postinst"), "configure"], check=True)


