def control():
    text = subprocess.run(["dpkg-deb", "-f", str(DEB)], check=True, capture_output=True, text=True).stdout
    return dict(line.split(": ", 1) for line in text.splitlines() if ": " in line)


def runs_as_root(unit: str) -> bool:
    """Same rule as czdev publish: root unless User=<non-root> or DynamicUser=yes in [Service]."""
    section, user, dynamic = None, None, False
    for line in unit.splitlines():
        line = line.strip()
        if line.startswith("["):
            section = line
        elif section == "[Service]" and "=" in line:
            k, v = (s.strip() for s in line.split("=", 1))
            if k == "User":
                user = v
            elif k == "DynamicUser":
                dynamic = v.lower() in ("yes", "true", "1")
    return not dynamic and (not user or user in ("root", "0"))


def test_service_not_root(tree):
    units = list((tree / "lib/systemd/system").glob("*.service"))
    assert [u.name for u in units] == ["pfadfinder-core.service"]
    unit = units[0].read_text()
    assert not runs_as_root(unit)
    assert "AmbientCapabilities=CAP_NET_ADMIN CAP_NET_RAW" in unit
    assert "RuntimeDirectory=pfadfinder" in unit
    groups = next(l for l in unit.splitlines() if l.startswith("SupplementaryGroups=")).split("=", 1)[1].split()
    assert "plugdev" in groups  # rtl-sdr udev rules give plugdev access to the stick


