        "import meshtastic.serial_interface, meshcore\n"
        "from meshtastic.protobuf import mesh_pb2\n"
        "m = mesh_pb2.FromRadio(); m.my_info.my_node_num = 0xdeadbeef\n"
        "assert mesh_pb2.FromRadio.FromString(m.SerializeToString()).my_info.my_node_num == 0xdeadbeef\n"
